export type DriverId =
  | "norris" | "piastri" | "verstappen" | "tsunoda" | "lawson"
  | "leclerc" | "hamilton" | "russell" | "antonelli"
  | "sainz" | "albon" | "alonso" | "stroll"
  | "gasly" | "colapinto" | "ocon" | "bearman"
  | "hulkenberg" | "bortoleto" | "hadjar";

export type TeamId =
  | "mclaren" | "redbull" | "ferrari" | "mercedes"
  | "williams" | "astonmartin" | "alpine" | "haas"
  | "sauber" | "racingbulls";

export type Driver = {
  id: DriverId;
  name: string;
  short: string; // 3-letter code
  team: TeamId;
  flag: string;  // flag emoji
};

export type Team = {
  id: TeamId;
  name: string;
  color: string; // hex
  drivers: DriverId[];
};

// One driver's result in a race
// position: 1–20, null = DNF/DNS
export type RaceEntry = {
  driverId: DriverId;
  position: number | null; // race position
  sprintPosition?: number | null; // sprint position (if applicable)
};

export type Race = {
  id: number;          // round number
  name: string;        // e.g. "Australian Grand Prix"
  shortName: string;   // e.g. "Australia"
  circuit: string;
  date: string;        // ISO yyyy-mm-dd
  hasSprint: boolean;
  results: RaceEntry[]; // sorted by position (DNF at the end)
};

